package game

import (
	"log"
	"time"

	"github.com/gdamore/tcell/v2"
)

// =============================================================================
// КОНСТАНТЫ ПОВЕДЕНИЯ МОНСТРА
// =============================================================================
const (
	// MonsterVisionRangeSq — квадрат радиуса зрения монстра (6^2 = 36).
	// Монстр начинает реагировать на игрока, если тот находится в пределах 6 клеток.
	MonsterVisionRangeSq = 36

	// 🆕 ЭТАП 3: Агрессивный радиус зрения (10^2 = 100).
	// Когда игрок несёт Амулет Бездны, монстры видят его в пределах 10 клеток.
	// Это делает побег с Амулетом сложнее и напряжённее.
	AggressiveVisionRangeSq = 100
)

// =============================================================================
// ОСОБЫЕ СВОЙСТВА БОССОВ
// =============================================================================
//
// Каждый босс может иметь одно особое свойство, которое активируется
// во время боя (в processTurn и monsterAttacksPlayer в combat.go).
type BossAbility int

const (
	BossAbilityNone          BossAbility = iota // нет особого свойства
	BossAbilityRegen                            // регенерация 3 HP каждый ход
	BossAbilityDoubleAttack                     // двойная атака по игроку
	BossAbilitySummon                           // призыв миньонов каждые 5 ходов
)

// =============================================================================
// СТРУКТУРА МОНСТРА
// =============================================================================
//
// Описывает врага в подземелье. Каждый монстр имеет:
//   - позицию на карте (X, Y)
//   - характеристики для боя (здоровье, атака)
//   - награду за убийство (золото, опыт)
//   - визуальное представление (символ и цвет для терминала)
//   - 🆕 поля для боссов (IsBoss, BossAbility, SummonCounter)
type Monster struct {
	X, Y      int         // координаты монстра на карте
	Name      string      // имя монстра (например, "Гоблин")
	HP        int         // текущее здоровье
	MaxHP     int         // максимальное здоровье (при создании)
	AttackVal int         // сила атаки (урон, наносимый игроку)
	GoldValue int         // количество золота, выпадающего при убийстве
	XPValue   int         // опыт за убийство (используется для повышения уровня игрока)
	Symbol    rune        // символ для отображения в терминале (например, 'g' для гоблина)
	Color     tcell.Color // цвет символа в терминале
	logger    *log.Logger // логгер для отладки (записывает действия монстра)

	// 🆕 Поля для боссов
	IsBoss        bool        // является ли монстр боссом
	BossAbility   BossAbility // особое свойство босса
	SummonCounter int         // счётчик ходов для призыва миньонов (только для боссов)
}

// =============================================================================
// КОНСТРУКТОР МОНСТРА
// =============================================================================
//
// Создаёт нового монстра с заданными характеристиками.
//
// Параметры:
//   - x, y: координаты на карте
//   - name: имя монстра
//   - hp: здоровье (одновременно и текущее, и максимальное)
//   - attack: сила атаки
//   - gold: золото при убийстве
//   - xp: опыт при убийстве
//   - symbol: символ для отображения
//   - color: цвет символа
//
// Возвращает указатель на созданного монстра.
func NewMonster(
	x, y int,
	name string,
	hp, attack, gold, xp int,
	symbol rune,
	color tcell.Color,
) *Monster {
	return &Monster{
		X:         x,
		Y:         y,
		Name:      name,
		HP:        hp,
		MaxHP:     hp, // при создании текущее здоровье равно максимальному
		AttackVal: attack,
		GoldValue: gold,
		XPValue:   xp,
		Symbol:    symbol,
		Color:     color,
	}
}

// =============================================================================
// КОНСТРУКТОР БОССА
// =============================================================================
//
// Создаёт босса с особыми свойствами. Боссы спавнятся на каждом 6-м уровне
// и охраняют лестницу вниз (см. spawnBoss в level_boss.go).
//
// Параметры:
//   - x, y: координаты на карте
//   - name: имя босса
//   - hp: здоровье
//   - attack: сила атаки
//   - gold: золото при убийстве
//   - xp: опыт при убийстве
//   - symbol: символ для отображения
//   - color: цвет символа
//   - ability: особое свойство босса
func NewBoss(
	x, y int,
	name string,
	hp, attack, gold, xp int,
	symbol rune,
	color tcell.Color,
	ability BossAbility,
) *Monster {
	return &Monster{
		X:             x,
		Y:             y,
		Name:          name,
		HP:            hp,
		MaxHP:         hp,
		AttackVal:     attack,
		GoldValue:     gold,
		XPValue:       xp,
		Symbol:        symbol,
		Color:         color,
		IsBoss:        true,
		BossAbility:   ability,
		SummonCounter: 0,
	}
}

// =============================================================================
// УСТАНОВКА ЛОГГЕРА
// =============================================================================
//
// Устанавливает логгер для монстра. Вызывается:
//   - после создания монстра (в spawnMonsters)
//   - после загрузки уровня из сохранения (в SetLogger уровня)
//
// Защита от паники: если монстр = nil, просто выходим без ошибок.
func (m *Monster) SetLogger(logger *log.Logger) {
	if m == nil {
		return
	}
	m.logger = logger
}

// =============================================================================
// ПОЛУЧЕНИЕ УРОНА
// =============================================================================
//
// Уменьшает здоровье монстра на заданное значение.
// Здоровье не может опуститься ниже 0 (защита от отрицательных значений).
//
// Все изменения логируются для отладки боя.
//
// Параметры:
//   - damage: количество урона, которое получает монстр
func (m *Monster) TakeDamage(damage int) {
	if m == nil {
		return
	}
	oldHP := m.HP // запоминаем старое значение для логирования
	m.HP -= damage
	if m.HP < 0 {
		m.HP = 0 // здоровье не может быть отрицательным
	}
	// Записываем в лог для отладки
	if m.logger != nil {
		m.logger.Printf("DAMAGE_TAKEN: %s получил %d урона. HP: %d -> %d",
			m.Name, damage, oldHP, m.HP)
	}
}

// =============================================================================
// АТАКА МОНСТРА
// =============================================================================
//
// Возвращает силу атаки монстра. Используется в функции
// `monsterAttacksPlayer` в combat.go для расчёта урона по игроку.
//
// Защита от паники: если монстр = nil, возвращает 0 (безопасно).
func (m *Monster) Attack() int {
	if m == nil {
		return 0
	}
	return m.AttackVal
}

// =============================================================================
// ИСКУССТВЕННЫЙ ИНТЕЛЛЕКТ МОНСТРА
// =============================================================================
//
// Вызывается каждый ход в `processTurn` для каждого монстра.
// Реализует простое преследование игрока.
//
// ⚠️ ВАЖНО: приёмник — УКАЗАТЕЛЬ (*Monster), иначе изменения координат
// применяются к копии, а оригинал в level.Monsters остаётся на месте!
//
// 🆕 ЭТАП 3: ПАРАМЕТР `aggressive`:
//   - false: обычный радиус зрения (6 клеток, MonsterVisionRangeSq)
//   - true: увеличенный радиус зрения (10 клеток, AggressiveVisionRangeSq)
//     Используется когда игрок несёт Амулет Бездны.
//
// АЛГОРИТМ ПОВЕДЕНИЯ:
//   1. Если игрок далеко (дистанция > радиуса зрения) — монстр стоит на месте
//   2. Если игрок вне поля зрения (за стеной) — монстр стоит на месте
//   3. Если игрок рядом и виден — монстр пытается приблизиться
//   4. Монстр НИКОГДА не заходит на клетку игрока (бой идёт отдельно)
//   5. Монстр не заходит на клетки других монстров
//
// Параметры:
//   - playerX, playerY: координаты игрока
//   - level: текущий уровень (для проверки проходимости и видимости)
//   - aggressive: 🆕 ЭТАП 3: увеличенный радиус зрения (когда игрок несёт Амулет)
func (m *Monster) AIUpdate(playerX, playerY int, level *Level, aggressive bool) {
	if m == nil || level == nil {
		return
	}

	distX := playerX - m.X
	distY := playerY - m.Y

	// 🆕 ЭТАП 3: Выбираем радиус зрения в зависимости от агрессивности
	// Когда игрок несёт Амулет Бездны, монстры видят дальше
	// Константы MonsterVisionRangeSq и AggressiveVisionRangeSq определены выше
	visionRangeSq := MonsterVisionRangeSq
	if aggressive {
		visionRangeSq = AggressiveVisionRangeSq
	}

	// Если игрок далеко, стоим на месте
	// Используем выбранный радиус зрения вместо магического числа 36
	if distX*distX+distY*distY > visionRangeSq {
		return
	}

	// Проверка видимости: монстр реагирует только если видит игрока
	// (не может видеть сквозь стены)
	// Функция CanSee определена в level_fov.go
	if !level.CanSee(m.X, m.Y, playerX, playerY) {
		return
	}

	dx, dy := 0, 0

	// Определяем направление движения по каждой оси:
	// +1 (вправо/вниз), -1 (влево/вверх), 0 (не двигаться)
	// Функция abs определена в combat.go
	if distX != 0 {
		dx = distX / abs(distX) // нормализация к +1 или -1
	}
	if distY != 0 {
		dy = distY / abs(distY) // нормализация к +1 или -1
	}

	// Пытаемся пойти по X
	newX := m.X + dx
	newY := m.Y

	// БЛОКИРОВКА: Нельзя идти на клетку игрока
	// (бой происходит через отдельный механизм атаки)
	if newX == playerX && newY == playerY {
		dx = 0
		newX = m.X
	}

	// Если клетка проходима и там нет другого монстра — двигаемся
	// Функции CanMoveTo и hasMonsterAt определены в level_queries.go
	if dx != 0 && level.CanMoveTo(newX, newY) && !level.hasMonsterAt(newX, newY) {
		if m.logger != nil {
			m.logger.Printf("AI_MOVE: %s двигается по X на (%d, %d)", m.Name, newX, newY)
		}
		m.X = newX
		return // уже сдвинулись, дальше не идём
	}

	// Пытаемся пойти по Y
	newX = m.X
	newY = m.Y + dy

	// БЛОКИРОВКА: Нельзя идти на клетку игрока
	if newX == playerX && newY == playerY {
		dy = 0
		newY = m.Y
	}

	if dy != 0 && level.CanMoveTo(newX, newY) && !level.hasMonsterAt(newX, newY) {
		if m.logger != nil {
			m.logger.Printf("AI_MOVE: %s двигается по Y на (%d, %d)", m.Name, newX, newY)
		}
		m.Y = newY
		return
	}
}

// =============================================================================
// ОТРИСОВКА МОНСТРА
// =============================================================================
//
// Рисует символ монстра в его координатах на экране.
//
// ВАЖНО: монстр рисуется только если клетка под ним видима
// (эта проверка делается в Level.Render, а не здесь).
//
// 🆕 АНИМАЦИЯ БОССА:
// Босс мигает между основным цветом и белым каждые 300 мс.
// Это создаёт эффект "пульсации" и выделяет босса среди обычных монстров.
// Анимация работает благодаря таймеру мигания (blinkEvent в game.go),
// который вызывает перерисовку экрана каждые 250 мс.
//
// Параметры:
//   - screen: экран для отрисовки
//   - offsetX, offsetY: смещение на экране (обычно 1, 0)
func (m *Monster) Render(screen tcell.Screen, offsetX, offsetY int) {
	if m == nil || screen == nil {
		return
	}

	fg := m.Color

	// 🆕 Анимация босса: пульсация цвета
	// Босс мигает между основным цветом и белым каждые 300 мс
	// Поле IsBoss определено в структуре Monster выше
	if m.IsBoss {
		phase := (time.Now().UnixNano() / int64(300*time.Millisecond)) % 2
		if phase == 1 {
			fg = tcell.ColorWhite // фаза 1 — белый (вспышка)
		}
	}

	// Формируем стиль: цвет монстра на чёрном фоне
	style := tcell.StyleDefault.
		Foreground(fg).
		Background(tcell.ColorBlack)

	// Рисуем символ монстра в его координатах
	screen.SetContent(
		m.X+offsetX,
		m.Y+offsetY,
		m.Symbol,
		nil,
		style,
	)
}