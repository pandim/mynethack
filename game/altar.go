package game

import (
	"github.com/gdamore/tcell/v2"
)

// =============================================================================
// СТРУКТУРА АЛТАРЯ
// =============================================================================
//
// Алтарь для благословения экипировки. Тратит золото на улучшение оружия/брони.
//
// ⚠️ АЛТАРЬ ОДНОРАЗОВЫЙ: после использования поле Used устанавливается в true,
// и повторное благословение невозможно. Это предотвращает бесконечное улучшение.
type Altar struct {
	X, Y int  // координаты на карте
	Used bool // использован ли алтарь (одноразовый)
}

// =============================================================================
// СОЗДАНИЕ АЛТАРЯ
// =============================================================================
func NewAltar(x, y int) *Altar {
	return &Altar{X: x, Y: y, Used: false}
}

// =============================================================================
// ОТРИСОВКА АЛТАРЯ
// =============================================================================
//
// Использованный алтарь отображается тусклым цветом.
func (a *Altar) Render(screen tcell.Screen, offsetX, offsetY int) {
	if a == nil || screen == nil {
		return
	}
	color := tcell.ColorWhite
	if a.Used {
		color = tcell.ColorDarkGray // использованный алтарь — тусклый
	}
	style := tcell.StyleDefault.
		Foreground(color).
		Background(tcell.ColorBlack)
	screen.SetContent(a.X+offsetX, a.Y+offsetY, '_', nil, style)
}