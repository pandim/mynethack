package game

import (
	"log"
	"time"

	"github.com/gdamore/tcell/v2"
)

// =============================================================================
// СТРУКТУРА ИГРОКА
// =============================================================================
//
// Главный герой игры. Содержит все характеристики, инвентарь и экипировку.
// Сохраняется в файл вместе с уровнями при сохранении игры.
type Player struct {
	X, Y      int     // координаты игрока на карте
	HP        int     // текущее здоровье
	MaxHP     int     // максимальное здоровье (растёт с уровнем)
	Level     int     // уровень персонажа (растёт от убийства монстров)
	XP        int     // накопленный опыт
	Gold      int     // количество золота
	AttackVal int     // сила атаки (базовая + бонус от оружия)
	Defense   int     // защита (базовая + бонус от брони)
	Hunger    int     // уровень голода (растёт с каждым шагом)
	Inventory []*Item // список предметов в инвентаре

	// Экипировка
	// Экипированные предметы НЕ занимают место в инвентаре
	// и дают постоянный бонус к характеристикам.
	//
	// ⚠️ МЕХАНИКА "УЛУЧШЕНИЯ":
	// При нахождении нового оружия/брони они НЕ заменяют текущие,
	// а УЛУЧШАЮТ их на +1. Новый предмет расходуется (уменьшается Count в стопке).
	// Это позволяет не переполнять инвентарь и даёт элемент прогрессии.
	EquippedWeapon *Item // экипированное оружие (бонус к атаке)
	EquippedArmor  *Item // экипированная броня (бонус к защите)

	// 🆕 ЭТАП 3: Амулет Бездны
	// Когда игрок подбирает Амулет Бездны (после убийства Короля Бездны),
	// это поле устанавливается в true. Монстры становятся агрессивнее.
	// Игрок должен вернуться на уровень 1 с Амулетом для победы.
	HasAmulet bool

	logger *log.Logger // логгер для отладки (записывает действия игрока)
}

// =============================================================================
// КОНСТРУКТОР ИГРОКА
// =============================================================================
//
// Создаёт нового игрока с заданными координатами.
//
// ⚠️ ВНИМАНИЕ: Значения характеристик здесь установлены НЕСТАНДАРТНО ВЫСОКИМИ
// (300 вместо обычных ~20-30). Это сделано специально для отладки/тестирования,
// чтобы игрок не умирал сразу при встрече с монстрами.
//
// Для нормальной игры значения стоит установить примерно так:
//   - HP/MaxHP: 30 (вместо 300)
//   - AttackVal: 5 (вместо 300)
//   - Defense: 2 (вместо 300)
//   - XP: 0 (вместо 300)
func NewPlayer(x, y int) *Player {
	return &Player{
		X:         x,
		Y:         y,
		HP:        20,
		MaxHP:     20,
		Level:     1,
		XP:        0,
		Gold:      0,
		AttackVal: 5,
		Defense:   2,
		Hunger:    0,
		Inventory: make([]*Item, 0), // пустой инвентарь
		HasAmulet: false,            // 🆕 ЭТАП 3: Амулет не подобран
	}
}

// =============================================================================
// УСТАНОВКА ЛОГГЕРА
// =============================================================================
//
// Устанавливает логгер для игрока. Вызывается:
//   - при создании новой игры (в startNewGame)
//   - после загрузки из сохранения (в loadGameFromMenu)
func (p *Player) SetLogger(logger *log.Logger) {
	if p == nil {
		return
	}
	p.logger = logger
}

// =============================================================================
// ПЕРЕМЕЩЕНИЕ ИГРОКА
// =============================================================================
//
// Перемещает игрока на (dx, dy) клеток и обновляет уровень голода.
//
// МЕХАНИКА ГОЛОДА:
//   - Каждый шаг увеличивает голод на 5
//   - При голоде > 1000 игрок начинает терять здоровье (умирает от голода)
//   - Голод можно утолить, съев предмет "Еда" из инвентаря
//
// Параметры:
//   - dx, dy: смещение по осям (-1, 0 или +1)
func (p *Player) Move(dx, dy int) {
	if p == nil {
		return
	}

	// Обновляем координаты
	p.X += dx
	p.Y += dy

	// Каждый шаг увеличивает голод
	p.Hunger += 5

	if p.logger != nil {
		p.logger.Printf("MOVE: Игрок переместился на (%d, %d). Голод: %d", p.X, p.Y, p.Hunger)
	}

	// Если голод превысил критический порог — игрок умирает от голода
	if p.Hunger > 1000 {
		p.HP -= 1       // теряем 1 HP за каждый ход после порога
		p.Hunger = 1000 // голод не растёт бесконечно
		if p.logger != nil {
			p.logger.Printf("STARVATION: Игрок умирает от голода! HP: %d", p.HP)
		}
	}
}

// =============================================================================
// АТАКА ИГРОКА
// =============================================================================
//
// Возвращает силу атаки игрока (базовая + бонус от оружия).
// Используется в функции `attackMonster` в combat.go.
func (p *Player) Attack() int {
	if p == nil {
		return 0
	}
	return p.AttackVal
}

// =============================================================================
// ВОССТАНОВЛЕНИЕ ЗДОРОВЬЯ
// =============================================================================
//
// Восстанавливает здоровье игрока на заданное количество.
// Здоровье не может превысить максимум (защита от переполнения).
//
// Параметры:
//   - amount: количество восстанавливаемого здоровья
func (p *Player) Heal(amount int) {
	if p == nil {
		return
	}
	oldHP := p.HP // запоминаем старое значение для логирования
	p.HP += amount
	// Здоровье не может превысить максимум
	if p.HP > p.MaxHP {
		p.HP = p.MaxHP
	}
	if p.logger != nil {
		p.logger.Printf("HEAL: Восстановлено %d HP. Было: %d, Стало: %d", amount, oldHP, p.HP)
	}
}

// =============================================================================
// ЭКИПИРОВКА ОРУЖИЯ (С МЕХАНИКОЙ "УЛУЧШЕНИЯ")
// =============================================================================
//
// ⚠️ ВАЖНО: эта функция НЕ удаляет предмет из инвентаря.
// Удалением (уменьшением Count) управляет useItem, чтобы корректно
// работать со стопками оружия и брони.
//
// МЕХАНИКА "УЛУЧШЕНИЯ":
//   - Если НЕТ экипированного оружия → экипировать новое (бонус = Value предмета)
//   - Если ЕСТЬ экипированное оружие → улучшить его на +1 ATK
//
// ПРИМЕР ИГРОВОГО ПРОЦЕССА:
//   Ход 1:  Нашёл "Меч" (+5 ATK) → Экипировал: ATK +5
//   Ход 15: Нашёл второй "Меч" → В инвентаре: "Меч x2"
//   Ход 16: Использовал меч → Улучшил первый: ATK +5 → +6, в инвентаре "Меч x1"
//
// Параметры:
//   - item: предмет-оружие для экипировки/улучшения
func (p *Player) EquipWeapon(item *Item) {
	if p == nil || item == nil {
		return
	}

	// Если НЕТ экипированного оружия — экипируем новое
	if p.EquippedWeapon == nil {
		p.EquippedWeapon = item
		p.AttackVal += item.Value
		if p.logger != nil {
			p.logger.Printf("EQUIP_WEAPON: %s экипировано. ATK: %d", item.Name, p.AttackVal)
		}
		return
	}

	// Если оружие УЖЕ есть — улучшаем его на +1
	oldValue := p.EquippedWeapon.Value
	p.EquippedWeapon.Value += 1
	p.AttackVal += 1
	if p.logger != nil {
		p.logger.Printf("UPGRADE_WEAPON: %s улучшено. ATK: %d -> %d",
			p.EquippedWeapon.Name, oldValue, p.EquippedWeapon.Value)
	}
}

// =============================================================================
// ЭКИПИРОВКА БРОНИ (С МЕХАНИКОЙ "УЛУЧШЕНИЯ")
// =============================================================================
//
// ⚠️ ВАЖНО: эта функция НЕ удаляет предмет из инвентаря.
// Удалением (уменьшением Count) управляет useItem, чтобы корректно
