// =============================================================================
// ПОЛУЧЕНИЕ ОПЫТА И ПОВЫШЕНИЕ УРОВНЯ
// =============================================================================
//
// Добавляет опыт за убийство монстра и проверяет, хватает ли его
// для повышения уровня.
//
// ФОРМУЛА ПОВЫШЕНИЯ УРОВНЯ:
//   - Порог опыта для уровня = Level * 20
//
// ПРИ ПОВЫШЕНИИ УРОВНЯ:
//   - Максимальное здоровье +5
//   - Текущее здоровье полностью восстанавливается
//   - Атака +1
//   - Защита +1
//
// Возвращает:
//   - true: уровень повысился
//   - false: уровень не повысился
func (p *Player) GainXP(amount int) bool {
	if p == nil || amount <= 0 {
		return false
	}

	p.XP += amount

	// Порог: level * 20
	threshold := p.Level * 20
	if p.XP >= threshold {
		// Вычитаем потраченный опыт (остаток сохраняется для следующего уровня)
		p.XP -= threshold
		// Повышаем уровень
		p.Level++
		// Бонусы за уровень
		p.MaxHP += 5     // максимум здоровья растёт
		p.HP = p.MaxHP   // полное восстановление при повышении уровня
		p.AttackVal += 1 // атака растёт
		p.Defense += 1   // защита растёт
		if p.logger != nil {
			p.logger.Printf("LEVEL_UP: Игрок достиг уровня %d. MaxHP=%d ATK=%d DEF=%d",
				p.Level, p.MaxHP, p.AttackVal, p.Defense)
		}
		return true
	}
	return false
}

// =============================================================================
// ОПЫТ ДО СЛЕДУЮЩЕГО УРОВНЯ
// =============================================================================
//
// Возвращает количество опыта, необходимое для достижения следующего уровня.
// Формула: Level * 20 (та же, что в GainXP)
func (p *Player) NextLevelXP() int {
	if p == nil {
		return 0
	}
	return p.Level * 20
}

// =============================================================================
// 🆕 ЭТАП 3: ПОДСЧЁТ РЕЛИКВИЙ
// =============================================================================
//
// CountRelics — возвращает количество УНИКАЛЬНЫХ реликвий в инвентаре.
// Используется в render.go → renderVictoryScreen для отображения прогресса
// коллекции реликвий (дополнительная цель игры).
//
// Подсчитываются только уникальные реликвии (по RelicID).
// Если в инвентаре две одинаковые реликвии, они считаются как одна.
//
// Константы ItemTypeRelic и RelicCount определены в item.go.
func (p *Player) CountRelics() int {
	if p == nil {
		return 0
	}

	// Используем множество для подсчёта уникальных реликвий
	// Поле RelicID определено в item.go
	seen := make(map[int]bool)
	for _, item := range p.Inventory {
		if item != nil && item.Type == ItemTypeRelic && item.RelicID >= 0 {
			seen[item.RelicID] = true
		}
	}

	return len(seen)
}

// =============================================================================
// ПРОВЕРКА КРИТИЧЕСКОГО СОСТОЯНИЯ
// =============================================================================
//
// Возвращает true, если игрок находится в критическом состоянии.
// Используется в `Render` для мигания символа '@' красным цветом.
//
// КРИТИЧЕСКИЕ УСЛОВИЯ:
//   - Здоровье меньше 20% от максимума
//   - Голод больше 800 (близко к смерти от голода)
func (p *Player) isCritical() bool {
	if p == nil {
		return false
	}

	// Проверка низкого здоровья (< 20%)
	if p.MaxHP > 0 {
		hpPercent := float64(p.HP) / float64(p.MaxHP)
		if hpPercent < 0.20 {
			return true
		}
	}

	// Проверка высокого голода (> 800)
	if p.Hunger > 800 {
		return true
	}

	return false
}

// =============================================================================
// ОТРИСОВКА ИГРОКА
// =============================================================================
//
// Рисует символ '@' в координатах игрока.
//
// ОСОБЕННОСТЬ: В критическом состоянии (низкое здоровье или голод)
// символ мигает, переключаясь между красным и зелёным цветом.
//
// 🆕 ЭТАП 3: Если игрок несёт Амулет Бездны, символ мигает золотым/белым.
// Это визуальный индикатор того, что игрок несёт Амулет.
//
// ⚠️ ПРИЁМНИК — УКАЗАТЕЛЬ (*Player) для консистентности со всеми другими
// методами Player и чтобы избежать случайного копирования структуры.
func (p *Player) Render(screen tcell.Screen, offsetX, offsetY int) {
	if p == nil || screen == nil {
		return
	}

	fg := tcell.ColorGreen // обычный цвет — зелёный

	// 🆕 ЭТАП 3: Если игрок несёт Амулет Бездны — мигаем золотым/белым
	// Это визуальный индикатор того, что игрок несёт Амулет
	// Поле HasAmulet определено в структуре Player выше
	if p.HasAmulet {
		phase := (time.Now().UnixNano() / int64(400*time.Millisecond)) % 2
		if phase == 0 {
			fg = tcell.ColorYellow // фаза 0 — золотой
		} else {
			fg = tcell.ColorWhite // фаза 1 — белый
		}
	} else if p.isCritical() {
		// Если игрок в критическом состоянии — мигаем красным/зелёным
		// time.Now().UnixNano() / 500ms даёт чередующееся число
		// % 2 определяет чётность → 0 или 1 → выбираем цвет
		phase := (time.Now().UnixNano() / int64(500*time.Millisecond)) % 2
		if phase == 0 {
			fg = tcell.ColorRed // фаза 0 — красный
		} else {
			fg = tcell.ColorGreen // фаза 1 — зелёный
		}
	}

	// Формируем стиль и рисуем символ '@'
	style := tcell.StyleDefault.
		Foreground(fg).
		Background(tcell.ColorBlack)

	screen.SetContent(
		p.X+offsetX,
		p.Y+offsetY,
		'@',
		nil,
		style,
	)
}