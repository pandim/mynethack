// UpdateFOV — обновляет поле зрения игрока (Field of View).
// Вызывается каждый кадр перед отрисовкой.
//
// Алгоритм:
//   1. Сбрасываем флаг Visible для всех клеток
//   2. Для каждой клетки в радиусе PlayerFOVRadius вокруг игрока проверяем:
//      - Находится ли клетка в круге радиуса PlayerFOVRadius
//      - Есть ли прямая видимость от игрока до этой клетки
//   3. Если оба условия выполнены — клетка видима и исследована
//
// Исследованные клетки (Explored) остаются на карте даже когда не видимы —
// они отображаются тусклым цветом.
func (l *Level) UpdateFOV(px, py int) {
	if l == nil {
		return
	}
	if px < 0 || px >= l.Width || py < 0 || py >= l.Height {
		return
	}

	// Используем константу вместо магического числа 8
	// (константа определена в level.go)
	radius := PlayerFOVRadius

	// Шаг 1: сбрасываем видимость для всех клеток
	for y := 0; y < l.Height; y++ {
		if y >= len(l.Tiles) {
			continue
		}
		for x := 0; x < l.Width; x++ {
			if x >= len(l.Tiles[y]) {
				continue
			}
			l.Tiles[y][x].Visible = false
		}
	}

	// Шаг 2: проверяем каждую клетку в квадрате вокруг игрока
	for y := py - radius; y <= py+radius; y++ {
		for x := px - radius; x <= px+radius; x++ {
			// Проверка границ карты
			if x < 0 || x >= l.Width || y < 0 || y >= l.Height {
				continue
			}
			if y >= len(l.Tiles) || x >= len(l.Tiles[y]) {
				continue
			}
			// Проверка расстояния (круг, а не квадрат)
			// Используем квадрат расстояния, чтобы не считать sqrt
			dist := (x-px)*(x-px) + (y-py)*(y-py)
			if dist <= radius*radius && l.hasLineOfSight(px, py, x, y) {
				l.Tiles[y][x].Visible = true  // видима прямо сейчас
				l.Tiles[y][x].Explored = true // запомнили навсегда
			}
		}
	}
}

// hasLineOfSight — проверяет, есть ли прямая видимость от (x0, y0) до (x1, y1).
//
// Использует алгоритм Брезенхема для построения линии между точками.
// Видимость блокируется стенами. Для диагональных шагов дополнительно
// проверяются обе соседние клетки (чтобы нельзя было "подглядывать" за угол).
//
// Алгоритм:
//   1. Строим линию от (x0, y0) до (x1, y1) по Брезенхему
//   2. Для каждой клетки на линии проверяем, прозрачна ли она
//   3. Для диагональных шагов проверяем обе соседние клетки
//      (чтобы стена блокировала диагональный обзор)
//   4. Если все клетки прозрачны — видимость есть
//
// Примечание: функция abs определена в combat.go
func (l *Level) hasLineOfSight(x0, y0, x1, y1 int) bool {
	if l == nil {
		return false
	}
	// Проверка границ
	if x0 < 0 || x0 >= l.Width || y0 < 0 || y0 >= l.Height {
		return false
	}
	if x1 < 0 || x1 >= l.Width || y1 < 0 || y1 >= l.Height {
		return false
	}
	// Одна и та же клетка — всегда видима
	if x0 == x1 && y0 == y1 {
		return true
	}

	// Алгоритм Брезенхема для построения линии
	dx := abs(x1 - x0)
	dy := abs(y1 - y0)
	sx := 1 // направление по X (+1 или -1)
	sy := 1 // направление по Y (+1 или -1)
	if x0 > x1 {
		sx = -1
	}
	if y0 > y1 {
		sy = -1
	}
	err := dx - dy // ошибка Брезенхема
	x, y := x0, y0

	for {
		e2 := 2 * err
		oldX, oldY := x, y // запоминаем текущую позицию до шага

		// Шаг по Брезенхему
		if e2 > -dy {
			err -= dy
			x += sx
		}
		if e2 < dx {
			err += dx
			y += sy
		}

		// Если сдвинулись по диагонали — проверяем обе соседние клетки.
		// Это предотвращает "подглядывание за угол" по диагонали.
		if x != oldX && y != oldY {
			if !l.isTransparent(oldX+sx, oldY) || !l.isTransparent(oldX, oldY+sy) {
				return false // стена блокирует диагональный обзор
			}
		}

		// Дошли до цели — видимость есть
		if x == x1 && y == y1 {
			return true
		}

		// Если текущая клетка непрозрачна (стена) — видимость заблокирована
		if !l.isTransparent(x, y) {
			return false
		}
	}
}

// isTransparent — прозрачна ли клетка для взгляда.
// В текущей реализации пол прозрачен, стена — нет.
// В будущем можно добавить полупрозрачные объекты (кусты, решётки и т.д.).
func (l *Level) isTransparent(x, y int) bool {
	return l.CanMoveTo(x, y)
}

// CanSee — публичный метод для проверки линии видимости.
// Используется монстрами в AIUpdate: монстр видит игрока только если
// между ними есть прямая видимость (не через стены).
func (l *Level) CanSee(x0, y0, x1, y1 int) bool {
	return l.hasLineOfSight(x0, y0, x1, y1)
}