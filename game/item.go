package game

import (
	"github.com/gdamore/tcell/v2"
)

// =============================================================================
// ТИПЫ ПРЕДМЕТОВ
// =============================================================================
//
// Использование по типам (в input.go → useItem):
//   - ItemTypePotion:  лечит здоровье (или утоляет голод, если имя = "Еда")
//   - ItemTypeWeapon:  экипируется как оружие, увеличивает атаку
//   - ItemTypeArmor:   экипируется как броня, увеличивает защиту
//   - ItemTypeGold:    автоматически добавляется в кошелёк при подборе
//   - ItemTypeRelic:   🆕 реликвия для продажи торговцу (дополнительная цель)
//   - ItemTypeScroll:  🆕 свиток с заклинанием (одноразовый)
//   - ItemTypeKey:     🆕 ключ для открытия золотых сундуков
//   - ItemTypeAmulet:  🆕 Амулет Бездны (финальный предмет)
type ItemType int

const (
	ItemTypePotion ItemType = iota // зелье (лечение) или еда (утоление голода)
	ItemTypeWeapon                 // оружие (бонус к атаке при экипировке)
	ItemTypeArmor                  // броня (бонус к защите при экипировке)
	ItemTypeGold                   // золото (автоматически в кошелёк)
	ItemTypeRelic                  // 🆕 реликвия (для продажи, дополнительная цель)
	ItemTypeScroll                 // 🆕 свиток (одноразовое заклинание)
	ItemTypeKey                    // 🆕 ключ (открывает золотые сундуки)
	ItemTypeAmulet                 // 🆕 Амулет Бездны (финальный предмет)
)

// =============================================================================
// 🆕 КОНСТАНТЫ РЕЛИКВИЙ
// =============================================================================
//
// Идентификаторы реликвий для отслеживания коллекции.
// Дополнительная цель игры — собрать все 5 реликвий одновременно.
//
// Реликвии можно продать торговцу (см. interact.go → sellRelic).
// Цена продажи хранится в поле Value.
const (
	RelicDiamond   = 0 // Алмаз
	RelicChalice   = 1 // Золотой кубок
	RelicCrown     = 2 // Корона гоблинов
	RelicStatuette = 3 // Древняя статуэтка
	RelicStarShard = 4 // Осколок звезды
	RelicCount     = 5 // общее количество реликвий в игре
)

// =============================================================================
// 🆕 КОНСТАНТЫ СВИТКОВ
// =============================================================================
//
// Типы свитков определяют эффект при использовании.
// Свитки — одноразовые предметы. Одинаковые свитки складываются в стопки.
//
// Эффекты свитков реализованы в combat.go → useScrollMap/Teleport/Lightning/Banishment.
const (
	ScrollMap        = 0 // Свиток карты: открывает весь этаж
	ScrollTeleport   = 1 // Свиток телепортации: случайное перемещение
	ScrollLightning  = 2 // Свиток молнии: урон всем монстрам на уровне
	ScrollBanishment = 3 // Свиток изгнания: уничтожает случайного монстра
	ScrollTypeCount  = 4 // общее количество типов свитков
)

// =============================================================================
// СТРУКТУРА ПРЕДМЕТА
// =============================================================================
//
// Поле `Value` — эффект предмета:
//   - Для зелий:    количество восстанавливаемого здоровья
//   - Для оружия:   бонус к атаке
//   - Для брони:    бонус к защите
//   - Для золота:   количество монет
//   - Для реликвий: 🆕 цена продажи торговцу
//   - Для свитков:  не используется (эффект определяется полем ScrollType)
//   - Для ключей:   не используется
//   - Для Амулета:  не используется
//
// Поле `Price` — цена в золоте (для товаров торговца).
// Обычные предметы на полу имеют Price = 0.
//
// Поле `Count` — количество предметов в стопке.
// Используется для расходников (зелья, еда, свитки, ключи) И оружия/брони.
//
// 🆕 Поле `RelicID` — идентификатор реликвии (константы Relic*).
// Используется для отслеживания коллекции. Для не-реликвий = -1.
//
// 🆕 Поле `ScrollType` — тип свитка (константы Scroll*).
// Определяет эффект при использовании. Для не-свитков = -1.
type Item struct {
	X, Y       int
	Name       string
	Type       ItemType
	Value      int         // эффект предмета (лечение, бонус атаки/защиты, цена реликвии)
	Price      int         // цена в золоте (для товаров торговца)
	Symbol     rune
	Color      tcell.Color
	Count      int         // количество предметов в стопке
	RelicID    int         // 🆕 идентификатор реликвии (0-4), -1 если не реликвия
	ScrollType int         // 🆕 тип свитка (0-3), -1 если не свиток
}

// =============================================================================
// КОНСТРУКТОР ПРЕДМЕТА
// =============================================================================
//
// Поля RelicID и ScrollType инициализируются значением -1.
func NewItem(
	x, y int,
	name string,
	itemType ItemType,
	value int,
	symbol rune,
	color tcell.Color,
) *Item {
	return &Item{
		X:          x,
		Y:          y,
		Name:       name,
		Type:       itemType,
		Value:      value,
		Price:      0,
		Symbol:     symbol,
		Color:      color,
		Count:      1,
		RelicID:    -1,
		ScrollType: -1,
	}
}

// =============================================================================
// 🆕 КОНСТРУКТОР РЕЛИКВИИ
// =============================================================================
//
// Создаёт реликвию с заданным идентификатором и ценой продажи.
// Реликвии НЕ стакаются (каждая уникальна) — см. IsStackable().
func NewRelic(x, y int, relicID int, name string, sellPrice int, symbol rune, color tcell.Color) *Item {
	return &Item{
		X:          x,
		Y:          y,
		Name:       name,
		Type:       ItemTypeRelic,
		Value:      sellPrice, // для реликций Value = цена продажи
		Price:      0,
		Symbol:     symbol,
		Color:      color,
		Count:      1,
		RelicID:    relicID,
		ScrollType: -1,
	}
}

// =============================================================================
// 🆕 КОНСТРУКТОР СВИТКА
// =============================================================================
//
// Создаёт свиток с заданным типом заклинания.
// Свитки стакаются (одинаковые свитки складываются в стопку).
func NewScroll(x, y int, scrollType int, name string, symbol rune, color tcell.Color) *Item {
	return &Item{
		X:          x,
		Y:          y,
		Name:       name,
		Type:       ItemTypeScroll,
		Value:      0,
		Price:      0,
		Symbol:     symbol,
		Color:      color,
		Count:      1,
		RelicID:    -1,
		ScrollType: scrollType,
	}
}

// =============================================================================
// 🆕 ПРОВЕРКА СТАКАЕМОСТИ
// =============================================================================
//
// Возвращает true, если предмет может складываться в стопки.
// Реликвии и Амулет НЕ стакаются (каждый экземпляр уникален).
// Все остальные предметы (зелья, еда, свитки, ключи, оружие, броня) стакаются.
//
// Используется в combat.go → addToInventoryWithStack.
func (i *Item) IsStackable() bool {
	if i == nil {
		return false
	}
	return i.Type != ItemTypeRelic && i.Type != ItemTypeAmulet
}

// =============================================================================
// ОТРИСОВКА ПРЕДМЕТА
// =============================================================================
func (i *Item) Render(screen tcell.Screen, offsetX, offsetY int) {
	if i == nil || screen == nil {
		return
	}
	style := tcell.StyleDefault.
		Foreground(i.Color).
		Background(tcell.ColorBlack)
	screen.SetContent(
		i.X+offsetX,
		i.Y+offsetY,
		i.Symbol,
		nil,
		style,
	)
}