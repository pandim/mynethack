package game

import (
	"math/rand"

	"github.com/gdamore/tcell/v2"
)

// =============================================================================
// СТРУКТУРА СУНДУКА
// =============================================================================
//
// Сундук с случайным содержимым: зелья, еда или монстр-ловушка.
//
// 🆕 ЗОЛОТЫЕ СУНДУКИ:
// Золотые сундуки (IsGolden = true) содержат более ценный лут:
// реликвии, свитки, большое количество золота.
// Для открытия золотого сундука нужен ключ (см. interact.go → openChest).
// Золотые сундуки отображаются золотым цветом.
type Chest struct {
	X, Y     int    // координаты на карте
	Opened   bool   // открыт ли сундук
	Contents string // тип содержимого: "potion", "food", "monster", "golden"
	// 🆕 Поле для золотых сундуков
	// Золотой сундук требует ключ для открытия.
	// Содержимое определяется при открытии (в interact.go → openChest).
	IsGolden bool // является ли сундук золотым (нужен ключ)
}

// =============================================================================
// СОЗДАНИЕ ОБЫЧНОГО СУНДУКА
// =============================================================================
//
// Создаёт обычный сундук со случайным содержимым.
// Содержимое определяется случайно: зелье, еда или монстр-ловушка.
// Обычные сундуки открываются без ключа.
func NewChest(x, y int) *Chest {
	// Случайное содержимое
	contents := []string{"potion", "food", "monster"}
	return &Chest{
		X:        x,
		Y:        y,
		Opened:   false,
		Contents: contents[rand.Intn(len(contents))],
		IsGolden: false, // обычный сундук
	}
}

// =============================================================================
// 🆕 СОЗДАНИЕ ЗОЛОТОГО СУНДУКА
// =============================================================================
//
// Создаёт золотой сундук с ценным содержимым.
// Золотой сундук требует ключ для открытия (см. interact.go → openChest).
//
// Содержимое определяется при открытии:
//   - 50% шанс: реликвия (случайная из 5 типов)
//   - 30% шанс: свиток (случайный из 4 типов)
//   - 20% шанс: большое количество золота (50-100 монет)
//
// Золотые сундуки спавнятся на уровнях 3+ (см. level_spawn.go → spawnGoldenChests).
func NewGoldenChest(x, y int) *Chest {
	return &Chest{
		X:        x,
		Y:        y,
		Opened:   false,
		Contents: "golden", // содержимое определяется при открытии
		IsGolden: true,     // нужен ключ для открытия
	}
}

// =============================================================================
// ОТРИСОВКА СУНДУКА
// =============================================================================
//
// Обычные сундуки отображаются жёлтым цветом.
// 🆕 Золотые сундуки отображаются золотым цветом (ярче, заметнее).
// Открытые сундуки отображаются тусклым цветом.
func (c *Chest) Render(screen tcell.Screen, offsetX, offsetY int) {
	if c == nil || screen == nil {
		return
	}
	color := tcell.ColorYellow // обычный сундук — жёлтый
	if c.IsGolden {
		// 🆕 Золотой сундук — золотой цвет
		// Используем RGB-цвет для точной передачи золотого оттенка.
		// Если терминал не поддерживает 24-битный цвет, tcell аппроксимирует.
		color = tcell.NewRGBColor(255, 215, 0) // RGB(255, 215, 0) = золотой
	}
	if c.Opened {
		color = tcell.ColorDarkGray // открытый сундук — тусклый
	}
	style := tcell.StyleDefault.
		Foreground(color).
		Background(tcell.ColorBlack)
	screen.SetContent(c.X+offsetX, c.Y+offsetY, '&', nil, style)
}